SELECT
	*
FROM
	CUSTOMERS
WHERE
	AGE = (
		SELECT
			MIN(AGE)
		FROM
			CUSTOMERS
	);

CREATE TABLE ORDERS (
	ID SERIAL PRIMARY KEY,
	AMOUNT INT,
	CUSTOMER_ID INT REFERENCES CUSTOMERS (ID)
);

